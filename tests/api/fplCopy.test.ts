import { describe, expect, test } from 'vitest';

import { fplCopyMail, messageHead, picOf } from '../../api/_lib/fplCopy';

// what autorouter transmitted for plan 512883 (its message queue), and the plan the app filed
const FILED =
  '(FPL-SXASV-VG\n-C172/L-SBDFGRY/EB1\n-LGTT2330\n-N0092VFR HOLARGOS HELLINIKON EASTAIGINA EASTPOROS EGN HELLINIKON\nHOLARGOS\n' +
  '-LGTT0059 LGMG\n-PBN/B2C2D2O2S1 NAV/SBAS OPR/AEROCLUB MESOGEION RMK/GARMIN GNS430W\nDOF/261119\n' +
  '-E/0320 P/002 R/E J/LF A/WHITE WITH BLUE STRIPES N/OPR TEL\n+302108169910 +306974776230 C/ZINDROS D +30 6942462092)';
const FULL =
  '(FPL-SXASV-VG\n-C172/L-SYBDFGR/EB1\n-LGTT2330\n-N0092VFR HOLARGOS HELLINIKON EASTAIGINA EASTPOROS EGN HELLINIKON HOLARGOS\n' +
  '-LGTT0059 LGMG\n-PBN/B2C2D2O2S1 NAV/SBAS DOF/261119 OPR/AEROCLUB MESOGEION ORGN/KSTPXAAP RMK/FILED VIA AUTOROUTER.AERO GARMIN GNS430W\n' +
  '-E/0320 P/002 R/E J/LF A/WHITE WITH BLUE STRIPES N/OPR TEL +302108169910 +306974776230 C/ZINDROS D +30 6942462092)';
const SHORT = FULL.replace(/\n-E\/[\s\S]*\)$/, ')');
const AT = Date.parse('2026-11-19T22:22:00Z');

describe('flight plan e-mail copy', () => {
  test('the head of an ATS message and the PIC of item 19', () => {
    expect(messageHead(FULL)).toEqual({ type: 'FPL', ident: 'SXASV', rules: 'V', dep: 'LGTT2330', dest: 'LGTT' });
    expect(messageHead('(CNL-SXASV-LGTT2330-LGTT-DOF/261119)')).toMatchObject({
      type: 'CNL',
      dep: 'LGTT2330',
      dest: 'LGTT',
    });
    expect(picOf(FILED)).toBe('ZINDROS D +30 6942462092');
    expect(picOf('(CNL-SXASV-LGTT2330-LGTT-DOF/261119)')).toBe('');
  });
  test('as EuroFPL lays it out: the fullest message autorouter sent, every addressee', () => {
    const m = fplCopyMail({
      kind: 'file',
      sent: [
        { text: SHORT, priority: 'FF', recipients: ['LGMGZTZX', 'LGMGZPZX'] },
        { text: FULL, priority: 'FF', recipients: ['LGATZAZV', 'LGGGZFZX', 'LGTTZTZX'] },
      ],
      fpl: FILED,
      addresses: ['LGGGZFZX'],
      at: AT,
    });
    expect(m.subject).toBe(
      '-TITLE ACK -MSGTYP VFPL SXASV LGTT2330 LGTT autorouter MSG -FILTIM 192222 -ORIGINDT 2611192222 (ZINDROS D +30 6942462092)',
    );
    expect(m.text).toBe(
      [
        "This message is automatically generated by Pig's Gotta Fly to serve as a filing confirmation.",
        '',
        '-BEGIN ADDR',
        '     -FAC KSTPXAAP',
        '-END ADDR',
        '-IFPLID VFR',
        `-MSGTXT ${FULL}`,
        '',
        'Original message addressees...',
        '',
        'FF LGMGZTZX LGMGZPZX LGATZAZV LGGGZFZX LGTTZTZX',
        '',
      ].join('\n'),
    );
  });
  test('without the queue: the plan and addressees the app sent; a cancellation', () => {
    const f = fplCopyMail({ kind: 'file', sent: [], fpl: FILED, addresses: ['LGGGZFZX', 'LGTTZTZX'], at: AT });
    expect(f.text).not.toContain('-BEGIN ADDR');
    expect(f.text).toContain(`-MSGTXT ${FILED}`);
    expect(f.text).toContain('FF LGGGZFZX LGTTZTZX');
    const c = fplCopyMail({
      kind: 'cancel',
      sent: [{ text: '(CNL-SXASV-LGTT2330-LGTT-DOF/261119)', priority: 'FF', recipients: ['LGTTZTZX'] }],
      fpl: FILED,
      addresses: [],
      at: AT,
    });
    expect(c.subject).toMatch(
      /^-TITLE ACK -MSGTYP CNL SXASV LGTT2330 LGTT autorouter MSG .*\(ZINDROS D \+30 6942462092\)$/,
    );
    expect(c.text).toMatch(/cancellation confirmation/);
    expect(c.text).not.toContain('-IFPLID');
  });
});
