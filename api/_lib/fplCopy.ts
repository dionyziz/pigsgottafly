// The e-mail copy of a filed flight plan (and of its delay or cancellation), for the operators and
// aerodromes that ask for one (operators.requires_fpl_copy, ref_aerodrome_contacts), laid out as the
// filing acknowledgements pilots know from EuroFPL:
//
//   subject  -TITLE ACK -MSGTYP VFPL SXASV LGTT1100 LGMG autorouter MSG -FILTIM 141022
//            -ORIGINDT 2611141022 (ZINDROS D +30 6942462092)
//   body     -BEGIN ADDR / -FAC <originator> / -END ADDR / -IFPLID VFR / -MSGTXT <the message>,
//            then the addressees it went to.
//
// The message and addressees are what autorouter transmitted (its message queue: it adds ORGN/ and
// its own addressees), or what was faxed and to whom; without them, the plan and addressees the app sent.
import type { FplCopyRecipient } from '../../src/shared/briefing.js';
import type { AftnMessage } from './autorouter.js';
import type { Queryable } from './db.js';

export type CopyKind = 'file' | 'delay' | 'cancel';

export interface CopyInput {
  kind: CopyKind;
  /** What autorouter transmitted (may be empty). */
  sent: AftnMessage[];
  /** The plan as filed and the app's addressees: the fallback, and where the PIC comes from. */
  fpl: string;
  addresses: string[];
  at: number;
  /** The backend that sent it (default autorouter). */
  via?: 'autorouter' | 'fax';
}

const PURPOSE: Record<CopyKind, string> = { file: 'filing', delay: 'delay', cancel: 'cancellation' };

const two = (n: number) => String(n).padStart(2, '0');
function stamp(ms: number): { filtim: string; origindt: string } {
  const d = new Date(ms);
  const ddhhmm = `${two(d.getUTCDate())}${two(d.getUTCHours())}${two(d.getUTCMinutes())}`;
  return { filtim: ddhhmm, origindt: `${two(d.getUTCFullYear() % 100)}${two(d.getUTCMonth() + 1)}${ddhhmm}` };
}

/** Type, aircraft, departure + time and destination of an ATS message: '(FPL-SXASV-VG …'. */
export function messageHead(text: string): { type: string; ident: string; dep: string; dest: string; rules: string } {
  const t = text.replace(/\s+/g, ' ');
  const m = /^\((\w{3})-([A-Z0-9]{2,7})-?([IVYZ])?/.exec(t);
  const dep = /-([A-Z]{4}\d{4})(?=[\s)-])/.exec(t);
  const rest = dep ? t.slice(dep.index + dep[0].length) : '';
  const dest = /-([A-Z]{4})(?:\d{4})?(?=[\s)-]|$)/.exec(rest);
  return { type: m?.[1] ?? '', ident: m?.[2] ?? '', rules: m?.[3] ?? '', dep: dep?.[1] ?? '', dest: dest?.[1] ?? '' };
}

/** The pilot in command as item 19 gives it (C/ to the end of the message). */
export function picOf(fpl: string): string {
  return /\bC\/([^)]*?)\s*\)?\s*$/.exec(fpl.replace(/\s+/g, ' '))?.[1].trim() ?? '';
}

export function fplCopyMail(i: CopyInput): { subject: string; text: string } {
  // the fullest message (the destination's alternates get one without item 19), and everyone it went to
  const msg = i.sent.length
    ? i.sent.reduce((a, b) => (b.text.length > a.text.length ? b : a))
    : { text: i.fpl, priority: 'FF', recipients: i.addresses };
  const recipients = i.sent.length ? [...new Set(i.sent.flatMap((s) => s.recipients))] : i.addresses;
  const h = messageHead(msg.text);
  const msgtyp = h.type === 'FPL' ? (h.rules === 'V' || h.rules === 'Z' ? 'VFPL' : 'IFPL') : h.type;
  const { filtim, origindt } = stamp(i.at);
  const pic = picOf(i.fpl);
  const subject = [
    '-TITLE ACK',
    `-MSGTYP ${msgtyp} ${h.ident} ${h.dep} ${h.dest} ${i.via ?? 'autorouter'} MSG`,
    `-FILTIM ${filtim}`,
    `-ORIGINDT ${origindt}`,
    pic ? `(${pic})` : '',
  ]
    .filter(Boolean)
    .join(' ');
  const orgn = /\bORGN\/([A-Z]{8})\b/.exec(msg.text)?.[1];
  const text = [
    `This message is automatically generated by Pig's Gotta Fly to serve as a ${PURPOSE[i.kind]} confirmation.`,
    '',
    ...(orgn ? ['-BEGIN ADDR', `     -FAC ${orgn}`, '-END ADDR'] : []),
    ...(msgtyp === 'VFPL' ? ['-IFPLID VFR'] : []),
    `-MSGTXT ${msg.text.trim()}`,
    '',
    'Original message addressees...',
    '',
    `${msg.priority} ${recipients.join(' ')}`,
    '',
  ].join('\n');
  return { subject, text };
}

/**
 * Who gets a copy of the flight's plan: its aircraft's operator when it asks for one, and the
 * aerodromes of the route (departure, stops, destination) listed in ref_aerodrome_contacts.
 */
export async function copyRecipients(
  db: Queryable,
  pilotId: string,
  flightId: string,
  routeIcaos: string[],
): Promise<FplCopyRecipient[]> {
  const out: FplCopyRecipient[] = [];
  const [op] = await db.query(
    `SELECT o.name, o.fpl_copy_email FROM flights f JOIN aircraft a ON a.id = f.aircraft_id JOIN operators o ON o.id = a.operator_id
     WHERE f.id = $1 AND f.pilot_id = $2 AND o.requires_fpl_copy`,
    [flightId, pilotId],
  );
  if (op?.fpl_copy_email) out.push({ email: op.fpl_copy_email, for: op.name });
  const icaos = [...new Set(routeIcaos)];
  if (icaos.length) {
    const rows = await db.query(
      'SELECT icao, fpl_copy_email FROM ref_aerodrome_contacts WHERE icao = ANY($1::text[]) AND fpl_copy_email <> $2',
      [icaos, ''],
    );
    for (const icao of icaos) {
      const r = rows.find((x) => x.icao === icao);
      if (r) out.push({ email: r.fpl_copy_email, for: icao });
    }
  }
  const by = new Map<string, FplCopyRecipient>();
  for (const r of out) {
    const k = r.email.toLowerCase();
    const cur = by.get(k);
    by.set(k, cur ? { ...cur, for: `${cur.for}, ${r.for}` } : r);
  }
  return [...by.values()];
}
