// Builds the native iPhone app's core (NATIVE.md): src/native/core/index.ts bundled by esbuild into
// native/ios/PigsGottaFly/Resources/core.js, an IIFE that sets globalThis.PGF, for JavaScriptCore
// (ES2020, minified). The file is committed, so building the app needs no Node.
//   npm run native:core              (write it)
//   npm run native:core -- --check   (fail when the committed file is not what the sources build)
// PGF.version is package.json's version and a hash of the bundle, so it changes with the code.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build, type Plugin } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CORE_ENTRY = path.join(ROOT, 'src/native/core/index.ts');
export const CORE_OUT = path.join(ROOT, 'native/ios/PigsGottaFly/Resources/core.js');
const PLACEHOLDER = '@@PGF_VERSION@@';
const BANNER =
  '// core.js: generated by `npm run native:core` (tools/build_native_core.ts) from src/native/core/. Do not edit.';

/** Our modules have no import side effects: what the core does not use is left out (the website's
 *  fetch, React and storage code next to the pure functions it shares). */
const pureSources: Plugin = {
  name: 'pure-sources',
  setup(b) {
    b.onResolve({ filter: /^\.\.?\// }, async (args) => {
      if (args.pluginData === 'resolved') return undefined;
      const r = await b.resolve(args.path, {
        kind: args.kind,
        importer: args.importer,
        resolveDir: args.resolveDir,
        pluginData: 'resolved',
      });
      if (r.errors.length) return { errors: r.errors };
      return { ...r, sideEffects: !r.path.startsWith(path.join(ROOT, 'src') + path.sep) };
    });
  },
};

/** The core.js text the sources build. */
export async function buildCore(): Promise<string> {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')) as { version: string };
  const r = await build({
    entryPoints: [CORE_ENTRY],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'PGF',
    target: 'es2020',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    define: { __PGF_VERSION__: JSON.stringify(PLACEHOLDER) },
    banner: { js: BANNER },
    footer: { js: 'globalThis.PGF=PGF;' },
    plugins: [pureSources],
    logLevel: 'silent',
  });
  const text = r.outputFiles[0].text;
  const hash = createHash('sha256').update(text).digest('hex').slice(0, 12);
  return text.replace(PLACEHOLDER, `${pkg.version}+${hash}`);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = await buildCore();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(CORE_OUT) ? fs.readFileSync(CORE_OUT, 'utf8') : '';
    if (current !== text) {
      console.error(`${path.relative(ROOT, CORE_OUT)} is stale: run npm run native:core`);
      process.exit(1);
    }
    console.log(`${path.relative(ROOT, CORE_OUT)} is up to date`);
  } else {
    fs.mkdirSync(path.dirname(CORE_OUT), { recursive: true });
    fs.writeFileSync(CORE_OUT, text);
    console.log(`${path.relative(ROOT, CORE_OUT)}: ${(text.length / 1024).toFixed(0)} KB`);
  }
}
