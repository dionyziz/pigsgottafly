"""Extract the GEN 2.7 sunrise/sunset tables (National Observatory of Athens, UTC) into data/sun.js.

Usage: python3 -I tools/parse_sun.py <LG_GEN_2_7_en.txt from pdftotext -layout> data/sun.js

Per aerodrome: ARP and, for every day of the (leap) "average year", sunset (SS) and end of civil
twilight, in minutes after 00:00 UTC. GEN 2.7.4: valid within a minute for 2024-2033.
"""
import json, re, sys

src, out = sys.argv[1], sys.argv[2]
MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
DAYS = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
mins = lambda t: int(t.split(':')[0]) * 60 + int(t.split(':')[1])
GROUP = re.compile(r'(\d{1,2})\s+(\d{1,2}:\d\d)\s+(\d{1,2}:\d\d)\s+(\d{1,2}:\d\d)\s+(\d{1,2}:\d\d)')

ads, cur, cols = {}, None, None
for line in open(src, encoding='utf-8', errors='replace').read().replace('Ν', 'N').replace('Ε', 'E').splitlines():
    m = re.match(r'^\s+(LG[A-Z]{2}) - (.+?)\s*$', line)
    if m and '....' not in line:
        cur = ads.setdefault(m[1], {'name': m[2], 'ss': {}, 'tw': {}})
        continue
    m = re.match(r'^\s+(\d{6})N\s+(\d{7})E\s*$', line)
    if m and cur is not None and 'lat' not in cur:
        a, b = m[1], m[2]
        cur['lat'] = round(int(a[:2]) + int(a[2:4]) / 60 + int(a[4:]) / 3600, 5)
        cur['lon'] = round(int(b[:3]) + int(b[3:5]) / 60 + int(b[5:]) / 3600, 5)
        continue
    names = [(line.index(n), n) for n in MONTHS if re.search(r'\b%s\b' % n, line)]
    if len(names) >= 2:
        cols = sorted(names)
        continue
    if cur is None or not cols:
        continue
    for g in GROUP.finditer(line):
        # which month column: the header whose centre is nearest to this group
        x = (g.start() + g.end()) / 2
        centres = [(p + len(n) / 2, n) for p, n in cols]
        month = min(centres, key=lambda c: abs(c[0] - x))[1]
        mi = MONTHS.index(month)
        day = int(g[1])
        if 1 <= day <= DAYS[mi]:
            cur['ss'][(mi, day)] = mins(g[4])
            cur['tw'][(mi, day)] = mins(g[5])

data, errors, corrections = {}, [], []
for icao, a in ads.items():
    ss, tw = [], []
    for mi, n in enumerate(DAYS):
        for d in range(1, n + 1):
            if (mi, d) not in a['ss']:
                errors.append(f'{icao} {MONTHS[mi]} {d} missing')
                ss.append(None); tw.append(None)
            else:
                ss.append(a['ss'][(mi, d)]); tw.append(a['tw'][(mi, d)])
    # isolated outliers in the source (e.g. LGAL 30 Nov repeats a late-October row): use the mean of
    # the neighbouring days, and report it
    for arr, what in ((ss, 'SS'), (tw, 'TWIL TO')):
        for i in range(1, len(arr) - 1):
            p, c, n = arr[i - 1], arr[i], arr[i + 1]
            if None not in (p, c, n) and abs(c - p) > 3 and abs(c - n) > 3 and abs(p - n) <= 3:
                arr[i] = round((p + n) / 2)
                corrections.append(f'{icao} day {i + 1} {what}: AIP {c // 60}:{c % 60:02d} -> {arr[i] // 60}:{arr[i] % 60:02d} (neighbours)')
    # sanity: sunset moves smoothly (< 3 min/day) and stays in a plausible window
    for i in range(1, len(ss)):
        if ss[i] is not None and ss[i - 1] is not None and abs(ss[i] - ss[i - 1]) > 3:
            errors.append(f'{icao} day {i}: jump {ss[i - 1]} -> {ss[i]}')
    if any(v is not None and not (14 * 60 <= v <= 18 * 60 + 30) for v in ss):
        errors.append(f'{icao}: sunset outside 14:00-18:30Z')
    data[icao] = {'lat': a.get('lat'), 'lon': a.get('lon'), 'ss': ss, 'tw': tw}
if errors:
    print('\n'.join(errors[:40])); sys.exit(1)
with open(out, 'w') as fh:
    fh.write('// Generated by tools/parse_sun.py from AIP GREECE GEN 2.7 (sunrise/sunset tables, UTC). Do not edit by hand.\n')
    fh.write('window.SUN = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(len(data), 'aerodromes'); print('\n'.join(corrections))
