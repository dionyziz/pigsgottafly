// Builds the native iPhone app's PDF page: the website's PDF entry (pdf.html →
// src/pdf/main.tsx, the export pages' own sheet components and CSS) built by Vite and inlined into one
// file, native/ios/PigsGottaFly/Resources/pdf/sheets.html, that the app's off-screen WKWebView loads
// as a string (Services/SheetRenderer.swift). One file because WebKit refuses module scripts and
// fonts from file:// URLs next to a page loaded that way; the fonts the CSS names in public/fonts
// become data: URLs. The file is committed, so building the app needs no Node.
//   npm run native:pdf              (write it)
//   npm run native:pdf -- --check   (fail when the committed file is not what the sources build)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import react from '@vitejs/plugin-react';
import { build, type Rollup } from 'vite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PDF_OUT = path.join(ROOT, 'native/ios/PigsGottaFly/Resources/pdf/sheets.html');
const FONTS = path.join(ROOT, 'public/fonts');
const BANNER =
  '<!-- sheets.html: generated by `npm run native:pdf` (tools/build_native_pdf.ts) from pdf.html and src/pdf/. Do not edit. -->';
const FONT_TYPES: Record<string, string> = { '.woff2': 'font/woff2', '.ttf': 'font/ttf' };

/** url('/fonts/X') → a data: URL of public/fonts/X. */
function inlineFonts(css: string): string {
  return css.replace(/url\((['"]?)\/fonts\/([\w.-]+)\1\)/g, (all, _q: string, name: string) => {
    const type = FONT_TYPES[path.extname(name).toLowerCase()];
    const file = path.join(FONTS, name);
    if (!type || !fs.existsSync(file)) throw new Error(`the CSS names a font that is not in public/fonts: ${all}`);
    return `url(data:${type};base64,${fs.readFileSync(file).toString('base64')})`;
  });
}

const IMAGE_TYPES: Record<string, string> = { '.svg': 'image/svg+xml', '.png': 'image/png' };

/**
 * '/icon.svg' in the sheet components' code → a data: URL of public/icon.svg. The website and the
 * server's Chromium load it from the site; the app's web view loads nothing, so the signatures'
 * watermark would be missing from the sheets printed on the device.
 */
export function inlinePublicImages(js: string): string {
  return js.replace(/(["'`])\/([\w.-]+\.(?:svg|png))\1/g, (all, q: string, name: string) => {
    const type = IMAGE_TYPES[path.extname(name).toLowerCase()];
    const file = path.join(ROOT, 'public', name);
    if (!type || !fs.existsSync(file)) return all;
    return `${q}data:${type};base64,${fs.readFileSync(file).toString('base64')}${q}`;
  });
}

/** A script's text that cannot end the inline <script> element early. */
const scriptSafe = (js: string) => js.replace(/<\/(script)/gi, '<\\/$1');

/** The sheets.html text the sources build. */
export async function buildPdfPage(): Promise<string> {
  const out = (await build({
    configFile: false,
    root: ROOT,
    logLevel: 'silent',
    plugins: [react()],
    publicDir: false,
    build: {
      write: false,
      outDir: fs.mkdtempSync(path.join(os.tmpdir(), 'pgf-native-pdf-')),
      emptyOutDir: false,
      sourcemap: false,
      modulePreload: false,
      cssCodeSplit: false,
      assetsInlineLimit: Number.MAX_SAFE_INTEGER,
      chunkSizeWarningLimit: 4000,
      rolldownOptions: { input: { pdf: path.join(ROOT, 'pdf.html') } },
    },
  })) as Rollup.RollupOutput | Rollup.RollupOutput[];
  const files = (Array.isArray(out) ? out : [out]).flatMap((o) => o.output);
  const byName = new Map(files.map((f) => [f.fileName, f]));
  const html = files.find((f) => f.fileName.endsWith('.html'));
  if (!html || html.type !== 'asset') throw new Error('Vite built no pdf.html');
  let page = String(html.source);
  const used = new Set<string>();
  page = page.replace(/<script\b[^>]*\bsrc="\/([^"]+)"[^>]*><\/script>/g, (_all, name: string) => {
    const f = byName.get(name);
    if (!f || f.type !== 'chunk') throw new Error(`pdf.html loads ${name}, which Vite did not build`);
    used.add(name);
    return `<script type="module">${scriptSafe(inlinePublicImages(f.code))}</script>`;
  });
  page = page.replace(/<link\b[^>]*\brel="stylesheet"[^>]*\bhref="\/([^"]+)"[^>]*>/g, (_all, name: string) => {
    const f = byName.get(name);
    if (!f || f.type !== 'asset') throw new Error(`pdf.html loads ${name}, which Vite did not build`);
    used.add(name);
    return `<style>${inlineFonts(String(f.source)).replace(/<\/(style)/gi, '<\\/$1')}</style>`;
  });
  // a chunk the page would fetch by itself (a dynamic import) could not load from a string
  const left = files.filter((f) => !f.fileName.endsWith('.html') && !used.has(f.fileName));
  if (left.length)
    throw new Error(`the PDF page needs more files than it inlines: ${left.map((f) => f.fileName).join(', ')}`);
  if (/\b(src|href)="\/(?!\/)/.test(page)) throw new Error('the PDF page still links a file by path');
  const img = /\bsrc:\s*["'`](\/[^/"'`][^"'`]*)/.exec(page);
  if (img) throw new Error(`the PDF page's code still loads ${img[1]} by path (put it in public/ to inline it)`);
  return `${BANNER}\n${page.trim()}\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = await buildPdfPage();
  const rel = path.relative(ROOT, PDF_OUT);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(PDF_OUT) ? fs.readFileSync(PDF_OUT, 'utf8') : '';
    if (current !== text) {
      console.error(`${rel} is stale: run npm run native:pdf`);
      process.exit(1);
    }
    console.log(`${rel} is up to date`);
  } else {
    fs.mkdirSync(path.dirname(PDF_OUT), { recursive: true });
    fs.writeFileSync(PDF_OUT, text);
    console.log(`${rel}: ${(text.length / 1024).toFixed(0)} KB`);
  }
}
